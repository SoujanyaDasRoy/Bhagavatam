DIG = str.maketrans('০১২৩৪৫৬৭৮৯', '0123456789')
BN = '০১২৩৪৫৬৭৮৯'

def parse_ch(v):
    if not v: return None
    if isinstance(v, int): return v
    s = str(v).strip()
    digits = ''.join(c.translate(DIG) for c in s if c in BN or c.isdigit())
    if digits: return int(digits)
    for k, num in BENGALI_ORDINALS.items():
        if k in s: return num
    return None

chapters_detected = []
cur_ch = 0

for p in range(129, 790):
    f = f"work/vision/v2_p{p:04d}.json"
    if not os.path.exists(f): continue
    d = json.load(open(f, encoding="utf-8"))
    ch = parse_ch(d.get("chapter_number"))
    tit = d.get("chapter_title") or ""
    sa = d.get("sanskrit_verse_numbers") or []
    has_v1 = (1 in sa) or any("॥ ১" in para or "॥ ১-" in para or "॥ ১–" in para for para in d.get("paragraphs", []))
    
    if (ch is not None or tit) and has_v1:
        detected_num = ch if ch else (cur_ch + 1)
        if detected_num != cur_ch:
            cur_ch = detected_num
            chapters_detected.append((p, cur_ch, tit[:30]))

print(f"Total chapters detected starting with verse 1: {len(chapters_detected)}")
for item in chapters_detected:
    print(f"p{item[0]:04d}: Ch {item[1]:02d} | {item[2]}")
